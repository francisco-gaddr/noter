/**
 * User-toggleable settings for the creative features (auto-link, flashcards, daily-review, voice,
 * spatial canvas). Pure + shared so web and mobile read/write the SAME shape and defaults; each app
 * persists the serialized blob in its own store (localStorage / AsyncStorage).
 *
 * AI features (flashcards, daily-review, voice transcription) each carry their OWN source + model
 * selection (`FeatureAiConfig`) so the user can pick local on-device, an API provider, or a custom
 * (Hermes) endpoint per feature — independent of the chat's selection.
 */

/** Where a feature's AI runs. Mirrors EmbeddingsConfig.source / AiTaskSource vocabulary. */
export type FeatureAiSource = 'local' | 'hermes' | 'api';

export interface FeatureAiConfig {
  source: FeatureAiSource;
  /** Provider id for api ('openai'…) / custom ('custom_x') / local engine ('mlc' | local model path). */
  provider?: string;
  model?: string;
}

export interface FeatureSettings {
  /** #1 Inline related/backlink suggestions while writing. Local lexical search — no AI cost. */
  autoLink: { enabled: boolean };
  /** #2 Spaced-repetition flashcards generated by AI from a note. */
  flashcards: { enabled: boolean; ai: FeatureAiConfig };
  /** #3 Daily review / resurface. Runs CLIENT-SIDE (E2E: the backend can't read note content). */
  dailyReview: { enabled: boolean; ai: FeatureAiConfig; surfaceCount: number };
  /** #5 Voice capture + transcription. On-device transcription needs a native module (no-EAS blocks
   *  it), so transcription goes through the selected provider. */
  voice: { enabled: boolean; ai: FeatureAiConfig };
  /** #4 Spatial canvas — global on/off; the per-note opt-in lives on the note (`canvasEnabled`). */
  canvas: { enabled: boolean };
}

export const defaultFeatureAiConfig = (): FeatureAiConfig => ({ source: 'api', provider: 'openai', model: '' });

export const defaultFeatureSettings = (): FeatureSettings => ({
  autoLink: { enabled: false },
  flashcards: { enabled: false, ai: defaultFeatureAiConfig() },
  dailyReview: { enabled: false, ai: defaultFeatureAiConfig(), surfaceCount: 5 },
  voice: { enabled: false, ai: defaultFeatureAiConfig() },
  canvas: { enabled: false },
});

const mergeAi = (raw: unknown): FeatureAiConfig => {
  const d = defaultFeatureAiConfig();
  if (!raw || typeof raw !== 'object') return d;
  const r = raw as Partial<FeatureAiConfig>;
  const source: FeatureAiSource = r.source === 'local' || r.source === 'hermes' || r.source === 'api' ? r.source : d.source;
  return {
    source,
    provider: typeof r.provider === 'string' ? r.provider : d.provider,
    model: typeof r.model === 'string' ? r.model : d.model,
  };
};

/** Tolerant parse: deep-merge over the defaults so a missing/extra key never breaks a new build. */
export const parseFeatureSettings = (raw: unknown): FeatureSettings => {
  const d = defaultFeatureSettings();
  let obj: any = raw;
  if (typeof raw === 'string') { try { obj = JSON.parse(raw); } catch { return d; } }
  if (!obj || typeof obj !== 'object') return d;
  const bool = (v: unknown, fallback: boolean) => (typeof v === 'boolean' ? v : fallback);
  return {
    autoLink: { enabled: bool(obj.autoLink?.enabled, d.autoLink.enabled) },
    flashcards: { enabled: bool(obj.flashcards?.enabled, d.flashcards.enabled), ai: mergeAi(obj.flashcards?.ai) },
    dailyReview: {
      enabled: bool(obj.dailyReview?.enabled, d.dailyReview.enabled),
      ai: mergeAi(obj.dailyReview?.ai),
      surfaceCount: Number.isFinite(obj.dailyReview?.surfaceCount) ? Math.max(1, Math.min(50, obj.dailyReview.surfaceCount)) : d.dailyReview.surfaceCount,
    },
    voice: { enabled: bool(obj.voice?.enabled, d.voice.enabled), ai: mergeAi(obj.voice?.ai) },
    canvas: { enabled: bool(obj.canvas?.enabled, d.canvas.enabled) },
  };
};

export const serializeFeatureSettings = (s: FeatureSettings): string => JSON.stringify(s);
