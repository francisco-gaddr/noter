const initI18n = async () => {
  let savedLanguage = await AsyncStorage.getItem('user-language');

  if (!savedLanguage) {
    const locales = Localization.getLocales();
    savedLanguage = locales && locales.length > 0 ? locales[0].languageCode : 'en';
  }

  await i18n.use(initReactI18next).init({
    resources,
    lng: savedLanguage || 'en',
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
    // Never render a raw dotted key when a translation is missing: return the provided
    // default (t(key, 'Default')) or '' so `t(key) || 'fallback'` resolves to the
    // fallback. A missing key degrades to readable text instead of "namespace.key".
    parseMissingKeyHandler: (_key: string, defaultValue?: string) => (typeof defaultValue === 'string' ? defaultValue : ''),
  });
};

initI18n();

export default i18n;
